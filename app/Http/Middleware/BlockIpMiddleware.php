namespace App\Http\Middleware;

use Closure;
use App\Models\BlockedIp;
use Illuminate\Http\Request;

class BlockIpMiddleware
{
    public function handle(Request $request, Closure $next)
    {
        // ?. ??????? IP ?????? ??? ????
        $userIp = $this->getUserIp($request);
        
        // ?. ??? ???? ?? IP ???? ??? ??? ????
        $blockedIp = BlockedIp::where('ip_address', $userIp)
                              ->where('active', 1)
                              ->first();
        
        // ?. IP ???? ????? ????????? ???? ????
        if ($blockedIp) {
            // ?? ???? ?? ???? IP ???? ????????? ???? ??????
            \Log::warning('Blocked IP attempted access', [
                'ip' => $userIp,
                'reason' => $blockedIp->reason,
                'attempted_url' => $request->fullUrl(),
                'user_agent' => $request->userAgent()
            ]);
            
            // JSON ??????? (AJAX ??????????? ????)
            if ($request->ajax() || $request->wantsJson()) {
                return response()->json([
                    'success' => false,
                    'message' => '????? IP ?????? ???? ??? ??????',
                    'reason' => $blockedIp->reason ?? '????????? ?????????'
                ], 403);
            }
            
            // ????? ????? ????
            abort(403, '????? IP ?????? ???? ??? ?????? ????: ' . ($blockedIp->reason ?? '????????? ?????????'));
        }
        
        return $next($request);
    }
    
    /**
     * ??????? ??? IP ?????? ??? ???? (???????/??? ??????????? ????????)
     */
    private function getUserIp(Request $request)
    {
        $ip = $request->ip();
        
        // CloudFlare ?? ???????? CDN ?? ??????? ????
        if ($request->hasHeader('CF-Connecting-IP')) {
            $ip = $request->header('CF-Connecting-IP');
        } elseif ($request->hasHeader('X-Forwarded-For')) {
            $ip = explode(',', $request->header('X-Forwarded-For'))[0];
        } elseif ($request->hasHeader('X-Real-IP')) {
            $ip = $request->header('X-Real-IP');
        }
        
        // IPv6 loopback ???
        if ($ip === '::1' || $ip === '127.0.0.1') {
            // ????? ????????????? ????
            return $ip;
        }
        
        return trim($ip);
    }
}